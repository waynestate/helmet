<?php

declare(strict_types=1);

namespace Waynestate\Helmet\Tests\Support;

use PHPUnit\Framework\TestCase;
use Waynestate\Helmet\Support\Setting;
use Waynestate\Playbook\Playbook;

require_once dirname(__DIR__) . '/fixtures/playbook-stub.php';

/**
 * Setting resolves one HELMET setting: the real environment first, then the
 * private waynestate/playbook package (stubbed in tests/fixtures), then
 * null. The stub stands in for the package, so no WSU value ever appears in
 * this public repo.
 */
final class SettingTest extends TestCase
{
    protected function setUp(): void
    {
        parent::setUp();
        $this->clear('HELMET_PRESET');
        Playbook::reset();
    }

    protected function tearDown(): void
    {
        $this->clear('HELMET_PRESET');
        Playbook::reset();
        parent::tearDown();
    }

    public function testEnvironmentBeatsPlaybook(): void
    {
        $this->put('HELMET_PRESET', 'citadel');
        Playbook::set('HELMET_PRESET', 'docker');

        self::assertSame('citadel', Setting::get('HELMET_PRESET'));
    }

    public function testPlaybookIsUsedWhenTheEnvironmentHasNoValue(): void
    {
        Playbook::set('HELMET_PRESET', 'citadel');

        self::assertSame('citadel', Setting::get('HELMET_PRESET'));
    }

    public function testPlaybookIsUsedWhenTheEnvironmentIsEmpty(): void
    {
        $this->put('HELMET_PRESET', '');
        Playbook::set('HELMET_PRESET', 'citadel');

        self::assertSame('citadel', Setting::get('HELMET_PRESET'));
    }

    public function testNeitherSourceGivesNull(): void
    {
        self::assertNull(Setting::get('HELMET_PRESET'));
    }

    public function testAnEmptyPlaybookValueGivesNull(): void
    {
        Playbook::set('HELMET_PRESET', '');

        self::assertNull(Setting::get('HELMET_PRESET'));
    }

    /**
     * The resolver is a copy of Playbook's, written by its generator: the
     * file carries the generator's header comment and HELMET's namespace, so
     * a hand rewrite shows up instead of sneaking in.
     */
    public function testSettingIsGeneratedFromPlaybook(): void
    {
        $root = dirname(__DIR__, 2);
        $source = (string) file_get_contents($root . '/src/Support/Setting.php');
        $lines = explode("\n", $source);
        $header = '// Generated by Playbook bin/setting-sync.php. Do not edit; run it again (php bin/setting-sync.php --write ...).';

        self::assertSame('<?php', $lines[0]);
        self::assertSame('declare(strict_types=1);', $lines[2]);
        self::assertSame($header, $lines[4]);
        self::assertStringContainsString('namespace Waynestate\Helmet\Support;', $source);
        self::assertLessThan(strpos($source, 'namespace Waynestate\Helmet\Support;'), strpos($source, $header));
    }

    /**
     * The check the CI job runs: from the repo root, the resolver, the wsu
     * values section and the manifest all agree with the tool.
     */
    public function testSettingCheckIsClean(): void
    {
        $root = dirname(__DIR__, 2);
        $run = $this->runSync($root . '/bin/setting-sync.php', ['--check'], $root);

        self::assertSame(0, $run['exit'], $run['output']);
    }

    /**
     * Drift is the whole point: a comment line appended by hand turns the
     * clean tree red, so nobody can "just tweak" the copy.
     */
    public function testHandEditIsDrift(): void
    {
        $root = dirname(__DIR__, 2);
        $temp = sys_get_temp_dir() . '/helmet-setting-drift-' . getmypid() . '-' . substr(md5((string) mt_rand()), 0, 8);

        try {
            foreach (['bin', 'src/Support', 'docs/guides'] as $dir) {
                mkdir($temp . '/' . $dir, 0775, true);
            }
            copy($root . '/bin/setting-sync.php', $temp . '/bin/setting-sync.php');
            copy($root . '/src/Support/Setting.php', $temp . '/src/Support/Setting.php');
            copy($root . '/docs/guides/wsu-values.md', $temp . '/docs/guides/wsu-values.md');
            copy($root . '/setting-sync.json', $temp . '/setting-sync.json');

            file_put_contents($temp . '/src/Support/Setting.php', "\n// A hand edit, the kind the check exists to catch.\n", FILE_APPEND);

            $run = $this->runSync($temp . '/bin/setting-sync.php', ['--check', '--root=' . $temp], $temp);

            self::assertSame(1, $run['exit'], $run['output']);
        } finally {
            $this->removeTree($temp);
        }
    }

    /**
     * Run the setting-sync tool with an argument array (no shell, every OS)
     * and return its exit code and combined output.
     *
     * @param list<string> $args
     */
    private function runSync(string $binary, array $args, string $cwd): array
    {
        $process = proc_open(
            array_merge([PHP_BINARY, $binary], $args),
            [
                0 => ['pipe', 'r'],
                1 => ['pipe', 'w'],
                2 => ['pipe', 'w'],
            ],
            $pipes,
            $cwd,
        );

        self::assertIsResource($process);

        fclose($pipes[0]);
        $stdout = (string) stream_get_contents($pipes[1]);
        $stderr = (string) stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);

        return ['exit' => proc_close($process), 'output' => $stdout . $stderr];
    }

    private function removeTree(string $dir): void
    {
        if (!is_dir($dir)) {
            return;
        }
        foreach ((array) scandir($dir) as $item) {
            if ($item === '.' || $item === '..') {
                continue;
            }
            $path = $dir . '/' . $item;
            if (is_dir($path)) {
                $this->removeTree($path);
            } else {
                @unlink($path);
            }
        }
        @rmdir($dir);
    }

    /**
     * Put a value in the global environment, the same way the Laravel tests
     * do (putenv plus both superglobals).
     */
    private function put(string $key, string $value): void
    {
        putenv("{$key}={$value}");
        $_ENV[$key] = $value;
        $_SERVER[$key] = $value;
    }

    private function clear(string $key): void
    {
        putenv($key);
        unset($_ENV[$key], $_SERVER[$key]);
    }
}
