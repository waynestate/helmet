<?php

declare(strict_types=1);

namespace Waynestate\Helmet\Logging;

use Monolog\Formatter\JsonFormatter;
use Monolog\Handler\FallbackGroupHandler;
use Monolog\Handler\StreamHandler;
use Monolog\LogRecord;
use Monolog\Logger;
use Psr\Log\LoggerInterface;

/**
 * Creates a structured (JSON) logger for HELMET.
 *
 * The logger writes one JSON object per line to the given stream or file, at
 * the given minimum level. JSON lines are easy to ship to a log aggregator
 * and to grep on the host.
 *
 * Two safety rules are built in:
 *
 *  - Secrets stay out of the logs. A processor redacts known sensitive keys
 *    (passwords, tokens, session IDs, keys, connection strings) from the
 *    record's context and extra before anything is written.
 *  - A logging failure never takes the request down. The configured stream is
 *    wrapped in a fallback group: if it cannot be written (unwritable file,
 *    full disk), the record is written to php://stderr instead.
 *
 * Every record also carries a request ID in extra.request_id, generated by
 * HELMET (never taken from an inbound header), so the lines of one request
 * can be tied together.
 */
final class Logging
{
    /**
     * The per-process request ID, generated on first use (see requestId()).
     */
    private static ?string $processRequestId = null;

    /**
     * Keys whose values are never written to the log, compared case-insensitively.
     *
     * @var list<string>
     */
    private const SENSITIVE_KEYS = [
        'password',
        'passwd',
        'pwd',
        'token',
        'access_token',
        'refresh_token',
        'api_token',
        'session_id',
        'sessionid',
        'sid',
        'secret',
        'client_secret',
        'api_key',
        'apikey',
        'private_key',
        'connection_string',
        'conn',
        'dsn',
    ];

    /**
     * Create a JSON logger.
     *
     * @param string $channel      The logger channel (usually the app name).
     * @param string $streamOrPath A stream (php://stderr) or a file path.
     * @param 'debug'|'info'|'notice'|'warning'|'error'|'critical'|'alert'|'emergency' $level
     *        Minimum level: debug, info, notice, warning, error, critical,
     *        alert or emergency.
     * @param string|null $requestId A request ID to stamp on every record.
     *        Used only when it looks like an ID (see isValidRequestId());
     *        otherwise the generated per-process ID is used. An inbound
     *        header is never trusted for this.
     */
    public static function create(
        string $channel,
        string $streamOrPath,
        string $level = 'info',
        ?string $requestId = null,
    ): LoggerInterface
    {
        $logger = new Logger($channel);

        $formatter = new JsonFormatter();

        $primary = new StreamHandler($streamOrPath, $level);
        $primary->setFormatter($formatter);

        // If the configured stream cannot be written, fall back to stderr so
        // a logging failure never takes the request down.
        $fallback = new StreamHandler('php://stderr', $level);
        $fallback->setFormatter($formatter);

        $logger->pushHandler(new FallbackGroupHandler([$primary, $fallback]));

        // Stamp every record with a request ID so the lines of one request
        // can be tied together. Pushed before redact: Monolog runs processors
        // in reverse push order, so redact still runs first and masks secrets
        // in the same record.
        if ($requestId !== null && self::isValidRequestId($requestId)) {
            $id = $requestId;
            $logger->pushProcessor(static fn (LogRecord $record): LogRecord => $record->with(extra: $record->extra + ['request_id' => $id]));
        } else {
            $logger->pushProcessor([self::class, 'addRequestId']);
        }

        // Keep secrets and session IDs out of the logs.
        $logger->pushProcessor([self::class, 'redact']);

        return $logger;
    }

    /**
     * The per-process request ID: 16 lowercase hex characters, generated on
     * first call and cached, so every record written by this PHP request
     * shares one ID. A CLI worker or other long-lived process keeps the ID
     * it got first; that is documented behaviour, not a bug to solve here.
     */
    public static function requestId(): string
    {
        if (self::$processRequestId === null) {
            self::$processRequestId = bin2hex(random_bytes(8));
        }

        return self::$processRequestId;
    }

    /**
     * Whether a caller-supplied value may be used as a request ID: 8 to 64
     * letters, digits, dots, underscores or dashes. Anything else is ignored
     * and the generated per-process ID is used instead.
     */
    public static function isValidRequestId(string $id): bool
    {
        return preg_match('/^[A-Za-z0-9._-]{8,64}$/', $id) === 1;
    }

    /**
     * Processor: stamp extra.request_id with the per-process request ID.
     */
    public static function addRequestId(LogRecord $record): LogRecord
    {
        return $record->with(extra: $record->extra + ['request_id' => self::requestId()]);
    }

    /**
     * Redact sensitive keys from the record's context and extra.
     */
    public static function redact(LogRecord $record): LogRecord
    {
        $context = $record->context;
        $extra = $record->extra;

        $newContext = self::redactArray($context);
        $newExtra = self::redactArray($extra);

        if ($newContext === $context && $newExtra === $extra) {
            return $record;
        }

        return $record->with(context: $newContext, extra: $newExtra);
    }

    /**
     * Replace the value of every sensitive key, at any depth.
     *
     * @param array<mixed> $data
     *
     * @return array<mixed>
     */
    private static function redactArray(array $data): array
    {
        foreach ($data as $key => $value) {
            if (is_string($key) && in_array(strtolower($key), self::SENSITIVE_KEYS, true)) {
                $data[$key] = '***';
            } elseif (is_array($value)) {
                $data[$key] = self::redactArray($value);
            }
        }

        return $data;
    }
}
